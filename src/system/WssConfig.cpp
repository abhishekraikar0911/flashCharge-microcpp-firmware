bool WSSConfig::init() {
    caCertificate = OCPP_SERVER_CA_CERT;
    return true;
}

WiFiClientSecure* WSSConfig::createSecureClient() {
    WiFiClientSecure* client = new WiFiClientSecure();
    
    if (!caCertificate.isEmpty()) {
        client->setCACert(caCertificate.c_str());
    }
    
    if (!clientCertificate.isEmpty() && !clientKey.isEmpty()) {
        client->setCertificate(clientCertificate.c_str());
        client->setPrivateKey(clientKey.c_str());
    }
    
    return client;
}

bool WSSConfig::setCACertificate(const char* caCert) {
    caCertificate = caCert;
    return true;
}

bool WSSConfig::setClientCertificate(const char* clientCert, const char* clientKey_) {
    clientCertificate = clientCert;
    clientKey = clientKey_;
    return true;
}

bool WSSConfig::validateCertificate(const char* fingerprint) {
    certFingerprint = fingerprint;
    return true;
}
